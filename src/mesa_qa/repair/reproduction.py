from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path
from typing import Any, Dict, List, Tuple

from mesa_qa.models import BugReport, ScenarioEvent


_TOOL_BY_ACTION = {
    "remember": "mesa_remember",
    "correct": "mesa_improve",
    "forget": "mesa_forget",
    "recall": "mesa_recall",
    "duplicate": "mesa_remember",
    "semantic_duplicate": "mesa_remember",
    "multi_fact": "mesa_remember",
    "conflict": "mesa_improve",
    "idempotency": "mesa_remember",
}


class ProductionReproducer:
    """Materialize a live-MCP regression in the isolated candidate only.

    The resulting test executes the recorded MESA launcher + Codex command and
    asserts on its freshly returned structured observation. It never determines
    failure from the saved expected/actual evidence alone.
    """

    def materialize(
        self,
        *,
        bug: BugReport,
        event: ScenarioEvent,
        candidate_worktree: Path,
        tester_workspace: Path,
        launcher_prefix: List[str],
        codex_binary: str,
        gateway_url: str,
        timeout_seconds: int,
    ) -> Tuple[str, Path, Dict[str, Any]]:
        candidate = Path(candidate_worktree).resolve()
        workspace = Path(tester_workspace).resolve()
        if not launcher_prefix:
            raise RuntimeError("Cannot materialize live reproduction without MESA launcher")
        if not workspace.is_dir():
            raise RuntimeError("Cannot materialize live reproduction without tester workspace")

        safe_id = re.sub(r"[^a-zA-Z0-9_]", "_", bug.bug_id.lower())
        rel_dir = Path("tests") / "mesa_qa_regressions"
        rel_test = rel_dir / f"test_{safe_id}.py"
        rel_spec = rel_dir / f"{safe_id}.reproduction.json"
        test_path = candidate / rel_test
        spec_path = candidate / rel_spec
        test_path.parent.mkdir(parents=True, exist_ok=True)

        head = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=candidate, capture_output=True,
            text=True, check=True,
        ).stdout.strip()
        tool = _TOOL_BY_ACTION.get(event.kind.value)
        if not tool:
            raise RuntimeError(f"No public MCP tool is defined for {event.kind.value}")

        parameters = {
            "entity": event.entity,
            "field": event.field,
            "value": event.value,
            "old_value": event.old_value,
            "text": event.text,
            "question": event.question,
            "mode": event.mode,
            "idempotency_key": event.idempotency_key,
        }
        action_id = f"reproduce_{bug.bug_id}"
        prompt = (
            "You are executing a MESA-QA regression against the configured MESA MCP "
            "server. Call exactly the required MESA MCP tool with the supplied semantic "
            "input. Return exactly one JSON object with action_id, scenario_event_id, "
            "tools_called, and actual. Do not claim success without calling the tool.\n"
            f"action_id: {action_id}\nscenario_event_id: {event.id}\n"
            f"required_tool: {tool}\nparameters: {json.dumps(parameters, sort_keys=True)}"
        )
        command = [
            *launcher_prefix,
            codex_binary,
            "exec",
            "--json",
            "--skip-git-repo-check",
            "--sandbox",
            "read-only",
            "-c",
            f'mcp_servers.mesa.url="{gateway_url.rstrip("/")}/mcp"',
            "-c",
            'mcp_servers.mesa.bearer_token_env_var="MESA_CODEX_MCP_TOKEN"',
            "-c",
            "mcp_servers.mesa.enabled=true",
            "-c",
            "mcp_servers.mesa.required=true",
            prompt,
        ]
        spec: Dict[str, Any] = {
            "bug_id": bug.bug_id,
            "candidate_sha": head,
            "scenario_id": bug.scenario_id,
            "runtime_event_id": event.id,
            "action_type": event.kind.value,
            "semantic_input": parameters,
            "expected_behavior": bug.expected,
            "observed_behavior": bug.actual,
            "tester_context_strategy": "fresh_thread",
            "idempotency_strategy": bug.reproduction_strategy,
            "required_mcp_tool": tool,
            "tester_workspace": str(workspace),
            "reproduction_command": command,
            "regression_path": str(rel_test),
            "timeout_seconds": timeout_seconds,
        }
        spec_path.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
        test_path.write_text(self._test_source(rel_spec.name), encoding="utf-8")
        return str(rel_test), spec_path, spec

    @staticmethod
    def _test_source(spec_name: str) -> str:
        return f'''# Generated by MESA-QA from a confirmed live anomaly. Do not edit manually.
import json
import subprocess
from pathlib import Path

SPEC = json.loads((Path(__file__).parent / {spec_name!r}).read_text(encoding="utf-8"))

def _walk(value):
    if isinstance(value, dict):
        yield value
        for child in value.values():
            yield from _walk(child)
    elif isinstance(value, list):
        for child in value:
            yield from _walk(child)
    elif isinstance(value, str):
        try:
            parsed = json.loads(value)
        except json.JSONDecodeError:
            return
        yield from _walk(parsed)

def _observation(stdout):
    for line in reversed(stdout.splitlines()):
        try:
            payload = json.loads(line)
        except json.JSONDecodeError:
            continue
        for item in _walk(payload):
            if item.get("action_id") == "reproduce_" + SPEC["bug_id"]:
                return item
    raise AssertionError("live Codex/MCP reproduction returned no matching observation")

def _normal(value):
    return " ".join(str(value).casefold().split())

def test_live_mcp_regression():
    result = subprocess.run(
        SPEC["reproduction_command"],
        cwd=SPEC["tester_workspace"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=SPEC["timeout_seconds"],
        check=False,
    )
    assert result.returncode == 0, result.stderr[-1000:]
    observation = _observation(result.stdout)
    assert SPEC["required_mcp_tool"] in observation.get("tools_called", [])
    actual = observation.get("actual", {{}})
    if SPEC["action_type"] in {{"remember", "correct", "forget", "duplicate", "semantic_duplicate", "multi_fact", "conflict", "idempotency"}}:
        assert actual.get("operation_state") == "COMMITTED", actual
    else:
        expected = SPEC["expected_behavior"].get("expected")
        candidates = [actual.get(key) for key in ("result", "answer", "value") if actual.get(key) is not None]
        assert any(_normal(candidate) == _normal(expected) for candidate in candidates), actual
'''
